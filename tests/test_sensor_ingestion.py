def test_raw_zip_untouched():
    with open(ZIP_PATH, "rb") as f:
        assert hashlib.sha256(f.read()).hexdigest() == ZIP_SHA256


def test_raw_csvs_untouched():
    for name in _csv_files():
        with open(os.path.join(CSV_DIR, name), "rb") as f:
            digest = hashlib.sha256(f.read()).hexdigest()
        assert digest == CSV_SHA256[name], name


def test_zip_contains_exactly_69_csvs():
    with zipfile.ZipFile(ZIP_PATH) as z:
        names = z.namelist()
    assert len(names) == 69
    assert set(names) == set(_csv_files())


