# ---------------------------------------------------------------------------
# 11. deterministic space IDs across extractions
# ---------------------------------------------------------------------------
def test_deterministic_space_ids(extracted):
    second = ext.build_outputs()
    a = [(s["space_id"], s) for s in extracted["spaces"]]
    b = [(s["space_id"], s) for s in second["spaces"]]
    assert a == b
    assert [st["id"] for st in extracted["storeys"]] == \
           [st["id"] for st in second["storeys"]]
    assert [bld["id"] for bld in extracted["buildings"]] == \
           [bld["id"] for bld in second["buildings"]]


# ---------------------------------------------------------------------------
# 12. JSON structure validation
# ---------------------------------------------------------------------------
def test_json_structure(reg, spaces_file):
    assert {"campus", "buildings", "storeys", "spaces", "metadata"} <= set(reg)
    c = reg["campus"]
    assert {"id", "name", "building_count", "storey_count", "space_count"} <= set(c)
    assert reg["campus"]["space_count"] == 115
    for b in reg["buildings"]:
        assert {"id", "campus_id", "name", "ifc_global_id"} <= set(b)
    for st in reg["storeys"]:
        assert STOREY_KEYS <= set(st)
    for s in reg["spaces"]:
        assert SPACE_KEYS <= set(s)
        assert s["ifc_global_id"]  # global ids never empty
    assert set(spaces_file.keys()) == {"spaces"}
    assert spaces_file["spaces"] == reg["spaces"]


def test_no_fabricated_sensor_links_in_spaces(reg):
    """Spaces carry no sensor references (nothing invented at foundation time)."""
    for s in reg["spaces"]:
        assert "sensor" not in {k.lower() for k in s["bim_properties"]}


