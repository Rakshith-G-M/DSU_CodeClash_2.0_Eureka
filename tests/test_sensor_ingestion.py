    assert {"task", "readings_location", "telemetry_reading_schema",
            "summary", "channels"} <= set(manifest)
    assert manifest["telemetry_reading_schema"]["columns"] == [
        "sensor_id", "timestamp", "value", "unit", "quality"]
    for c in manifest["channels"]:
        assert CHANNEL_KEYS <= set(c)


